def po_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def fill(path: Path) -> tuple[int, list[str]]:
    blocks = path.read_text(encoding="utf-8").split("\n\n")
    missing, done = [], 0
    for i, block in enumerate(blocks):
        m = re.search(r'^msgid ((?:".*"\n?)+)', block, re.M)
        if not m or i == 0:
            continue
        msgid = "".join(re.findall(r'"(.*)"', m.group(1))).replace('\\"', '"')
        if msgid not in PT:
            missing.append(msgid)
            continue
        value = PT[msgid]
        block = re.sub(r"^#, fuzzy.*\n", "", block, flags=re.M)
        block = re.sub(r"^#\| .*\n", "", block, flags=re.M)
        if isinstance(value, tuple):
            block = re.sub(
                r'^msgstr\[0\] (".*"\n?)+',
                f'msgstr[0] "{po_escape(value[0])}"\n',
                block,
                flags=re.M,
            )
            block = re.sub(
                r'^msgstr\[1\] (".*"\n?)+', f'msgstr[1] "{po_escape(value[1])}"', block, flags=re.M
            )
        else:
            block = re.sub(r'^msgstr (".*"\n?)+', f'msgstr "{po_escape(value)}"', block, flags=re.M)
        blocks[i] = block.rstrip("\n")
        done += 1
    text = "\n\n".join(blocks)
    text = text.replace(
        '"Plural-Forms: nplurals=INTEGER; plural=EXPRESSION;\\n"',
        '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"',
    )
    text = text.replace('"Language: \\n"', '"Language: pt\\n"')
    path.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")
    return done, missing


if __name__ == "__main__":
    po = Path(__file__).resolve().parent.parent / "locale/pt/LC_MESSAGES/django.po"
    done, missing = fill(po)
    print(f"translated {done}; missing {len(missing)}")
    for m in missing:
        print("  MISSING:", m)
    sys.exit(1 if missing else 0)
